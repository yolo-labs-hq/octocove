#!/usr/bin/env node
// Generates the committed client modules from the Octocove API contract, supplied with `--spec PATH`
// (the contract is maintained with the hosted service, not in this repository):
//   src/generated/openapi.ts  — openapi-typescript `paths`/`components`/`operations` (types only)
//   src/generated/routing.ts  — operationId → method, path template, server base path, parameter
//                               locations, media types, statuses, joined with retry-policy.json
//   src/generated/meta.ts     — OpenAPI info.version, document digest and generator revisions
// `--check --spec PATH` regenerates in memory and fails when any committed file differs (the drift
// check the contract's maintainers run). `--check` alone checks what this repository holds: the
// policy join, the operation set, the build record and the digest of the generated output.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { parse } from 'yaml';

const here = (path) => fileURLToPath(new URL(path, import.meta.url));
const specFlag = process.argv.indexOf('--spec');
if (specFlag !== -1 && !process.argv[specFlag + 1]) {
  process.stderr.write('generate: --spec needs a path\n');
  process.exit(1);
}
const SPEC = specFlag === -1 ? null : process.argv[specFlag + 1];
const POLICY = here('../retry-policy.json');
const MANIFEST = here('../package.json');
const OUT = {
  openapi: here('../src/generated/openapi.ts'),
  routing: here('../src/generated/routing.ts'),
  meta: here('../src/generated/meta.ts'),
};
// Bump when this script's output shape changes; recorded in the manifest and at runtime.
const ROUTING_GENERATOR = 'octocove-client-routing@1';
const METHODS = ['get', 'put', 'post', 'delete', 'patch', 'head', 'options'];
const HEADER = '// Generated by packages/client/scripts/generate.mjs from the Octocove API contract. Do not edit;\n'
  + '// run `pnpm --filter ./packages/client generate -- --spec PATH`. CI fails when this file is stale.\n';

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
const pinned = manifest.devDependencies['openapi-typescript'];
const installed = createRequire(import.meta.url)('openapi-typescript/package.json').version;
if (installed !== pinned) fail(`openapi-typescript ${installed} is installed but ${pinned} is pinned; run pnpm install --frozen-lockfile`);
const GENERATOR = `openapi-typescript@${pinned}`;

const policy = JSON.parse(readFileSync(POLICY, 'utf8'));

/** Digest of the generated types and routing, recorded in meta.ts so edits to either are detectable. */
function outputDigest(openapiText, routingText) {
  return createHash('sha256').update(openapiText).update('\0').update(routingText).digest('hex');
}

/** The operationIds the generated types declare (`export interface operations`). */
function typedOperations(text) {
  const start = text.indexOf('\nexport interface operations {\n');
  if (start === -1) return null;
  const end = text.indexOf('\n}\n', start + 1);
  return [...text.slice(start, end === -1 ? undefined : end).matchAll(/^ {4}([A-Za-z0-9_]+): \{$/gm)].map((m) => m[1]);
}

/** The routing table a committed routing.ts carries (JSON between the export and `as const`). */
function committedRouting(text) {
  const start = text.indexOf('export const routing = ');
  const end = text.indexOf(' as const satisfies');
  if (start === -1 || end === -1) return null;
  try { return JSON.parse(text.slice(start + 'export const routing = '.length, end)); } catch { return null; }
}

const committedDigest = (() => {
  try { return /"openapiSha256": "([0-9a-f]{64})"/.exec(readFileSync(OUT.meta, 'utf8'))?.[1] ?? null; } catch { return null; }
})();

if (SPEC === null) {
  if (!process.argv.includes('--check')) fail('--spec PATH is required: the API contract is not in this repository');
  // No contract here: check the parts this repository owns.
  const problems = [];
  const read = (path) => { try { return readFileSync(path, 'utf8'); } catch { return null; } };
  const [openapiText, routingText, metaText] = [read(OUT.openapi), read(OUT.routing), read(OUT.meta)];
  const table = routingText === null ? null : committedRouting(routingText);
  if (!table) problems.push('src/generated/routing.ts does not carry a parseable routing table');
  else {
    for (const id of Object.keys(policy)) if (!table[id]) problems.push(`retry-policy.json names ${id}, which routing.ts lacks`);
    for (const [id, entry] of Object.entries(table)) {
      if (JSON.stringify(entry.policy) !== JSON.stringify(policy[id])) problems.push(`routing.ts ${id} policy differs from retry-policy.json`);
    }
    // openapi-typescript types path and webhook operations alike under `operations`.
    const typed = openapiText === null ? null : typedOperations(openapiText);
    const routed = Object.keys(table).sort();
    if (!typed) problems.push('src/generated/openapi.ts does not declare its operations');
    else if (JSON.stringify([...typed].sort()) !== JSON.stringify(routed)) problems.push('openapi.ts and routing.ts declare different operations');
  }
  const recordedOutput = metaText === null ? null : /"outputSha256": "([0-9a-f]{64})"/.exec(metaText)?.[1];
  if (openapiText === null || routingText === null || recordedOutput !== outputDigest(openapiText, routingText)) {
    problems.push('openapi.ts or routing.ts was edited after generation (meta.ts outputSha256 differs)');
  }
  for (const path of Object.values(OUT)) {
    try { if (!readFileSync(path, 'utf8').startsWith(HEADER)) problems.push(`${path.slice(path.indexOf('src/'))} header`); }
    catch { problems.push(`${path.slice(path.indexOf('src/'))} missing`); }
  }
  const recorded = metaText === null ? {} : {
    openapiVersion: /"openapiVersion": "([^"]*)"/.exec(metaText)?.[1],
    generator: /"generator": "([^"]*)"/.exec(metaText)?.[1],
    routingGenerator: /"routingGenerator": "([^"]*)"/.exec(metaText)?.[1],
  };
  if (recorded.generator !== GENERATOR || recorded.routingGenerator !== ROUTING_GENERATOR) problems.push('meta.ts generator revisions differ from the pinned generator');
  if (JSON.stringify(manifest.octocove) !== JSON.stringify(recorded)) problems.push('package.json "octocove" build record differs from meta.ts');
  if (problems.length) fail(`generated client output is inconsistent: ${problems.join('; ')}`);
  process.stdout.write(`Generated client is consistent (API contract ${(committedDigest ?? '').slice(0, 12)}, OpenAPI ${recorded.openapiVersion}): the policy join, operation set, build record and output digest. Pass --spec with that contract for the full drift check.
`);
  process.exit(0);
}

const source = readFileSync(SPEC, 'utf8');
const doc = parse(source);

// Delivery labels the contract's maintainers use to track work items and open questions: a letter (G, O or Q) and a
// number, a range of them, or P<n>-<n>. They mean nothing to a client.
const LABEL = String.raw`(?:[GOQ]\d{1,2}(?:-[GOQ]?\d{1,2})?|P\d-\d{1,2})`;
// The words such a parenthetical may hold besides labels and still say nothing to a client ("<label> for a new execution").
const LABEL_FILLER = new Set(['for', 'a', 'new', 'execution', 'refresh', 'and', 'scope', 'expansion', 'retiring', 'retired', 'are']);
/** Drops delivery labels: a parenthetical of labels only, a trailing `, <label>` inside a clause, `is <label>;`, `until <label>`. */
function withoutLabels(text) {
  const label = new RegExp(String.raw`\b${LABEL}\b`);
  return text
    .replace(/\s*\(([^()]*)\)/g, (whole, inner) => {
      if (!label.test(inner)) return whole;
      const rest = inner.replace(new RegExp(String.raw`\b${LABEL}\b`, 'g'), ' ').split(/[\s,;/]+/).filter(Boolean);
      return rest.every((word) => LABEL_FILLER.has(word)) ? '' : whole;
    })
    .replace(new RegExp(String.raw`\bthe fresh delegation ${LABEL} requires\b`, 'g'), 'the fresh delegation a reopened lane requires')
    .replace(new RegExp(String.raw`\bthe ${LABEL} path:\s*`, 'g'), '')
    .replace(new RegExp(String.raw`\bthe ${LABEL} path\b`, 'g'), 'the candidate-per-submission path')
    .replace(new RegExp(String.raw`\bis ${LABEL};`, 'g'), 'is not available yet;')
    .replace(new RegExp(String.raw`\s+until ${LABEL}\b`, 'g'), ' for now')
    .replace(new RegExp(String.raw`\(${LABEL}(?:,\s*${LABEL})*;\s*`, 'g'), '(')
    .replace(new RegExp(String.raw`,\s*${LABEL}(?:,\s*${LABEL})*(?=[);])`, 'g'), '')
    .replace(new RegExp(String.raw`;\s*(?:ADR[- ]?\d{1,4}\s+)?${LABEL}(?:,\s*${LABEL})*:\s*`, 'g'), '; ');
}
/** Contract prose as the published types carry it: references to design records and documents kept with the hosted
 * service and delivery labels are dropped, since this repository does not include them. Deterministic, so the drift check sees the same output. */
function publicText(text) {
  const out = withoutLabels(text)
    .replace(/\s*\([^()]*\bADR[- ]?\d{1,4}\b[^()]*\)/g, '')
    // "bound under <record>, ..." loses the whole phrase; "Under <record> protected-runtime admission" keeps "Under".
    .replace(/\s*\b(?:under|per|see|in|by|from|via|following)\s+ADR[- ]?\d{1,4}\b(?=\s*(?:[,.;:)]|$|(?:whose|which|that|and)\b))/gi, '')
    .replace(/\bADR[- ]?\d{1,4}\b[:.,]?\s*/g, '')
    // Citations of the service's own documents, which this repository does not include.
    .replace(/\s*\([^()]*\b(?:docs\/(?:API|AUTH)\.md|COLLABORATION_RECORD\.md)[^()]*\)/g, '')
    .replace(/;\s*see\s+(?:docs\/(?:API|AUTH)\.md|COLLABORATION_RECORD\.md)(?:\s+section\s+\d+)?\./gi, '.')
    .replace(/\s*\bSee\s+(?:docs\/(?:API|AUTH)\.md|COLLABORATION_RECORD\.md)(?:\s+section\s+\d+)?\./g, '')
    .replace(/\s+(?:in|see)\s+(?:docs\/(?:API|AUTH)\.md|COLLABORATION_RECORD\.md)(?:\s+section\s+\d+)?/gi, '')
    .replace(/[ \t]{2,}/g, ' ').replace(/ +([.,;:])/g, '$1').replace(/\( /g, '(').replace(/ \)/g, ')')
    // A sentence left starting with the dash that followed a dropped label: "... settles. - on a lane" reads "... settles. On a lane".
    .replace(/(^|[.;]\s+)-\s+([a-z])/g, (_, before, c) => before + c.toUpperCase());
  return text !== out ? out.replace(/^([a-z])/, (c) => c.toUpperCase()) : out;
}
function publicContract(node) {
  if (Array.isArray(node)) return node.map(publicContract);
  if (!node || typeof node !== 'object') return node;
  return Object.fromEntries(Object.entries(node).map(([key, value]) =>
    [key, (key === 'description' || key === 'summary') && typeof value === 'string' ? publicText(value) : publicContract(value)]));
}

function fail(message) {
  process.stderr.write(`generate: ${message}\n`);
  process.exit(1);
}

function deref(node) {
  let current = node;
  for (let hops = 0; current && typeof current.$ref === 'string'; hops++) {
    if (hops > 16 || !current.$ref.startsWith('#/')) fail(`unsupported $ref ${current.$ref}`);
    current = current.$ref.slice(2).split('/').reduce((value, key) => value?.[key.replace(/~1/g, '/').replace(/~0/g, '~')], doc);
  }
  if (!current) fail(`unresolved $ref ${node.$ref}`);
  return current;
}

function basePath(servers) {
  const url = servers?.[0]?.url;
  if (typeof url !== 'string') fail('no server url');
  return new URL(url).pathname.replace(/\/+$/, '');
}

function route(operationId, method, path, pathItem, operation, kind) {
  const params = new Map();
  for (const raw of [...(pathItem.parameters ?? []), ...(operation.parameters ?? [])]) {
    const param = deref(raw);
    params.set(`${param.in}:${param.name}`, param);
  }
  const parameters = { path: [], query: [], header: [], cookie: [] };
  for (const param of params.values()) {
    if (!(param.in in parameters)) fail(`${operationId}: parameter location ${param.in}`);
    parameters[param.in].push({ name: param.name, required: param.required === true });
  }
  for (const list of Object.values(parameters)) list.sort((a, b) => a.name.localeCompare(b.name));
  const body = operation.requestBody ? deref(operation.requestBody) : undefined;
  const responses = {};
  for (const [status, raw] of Object.entries(operation.responses ?? {}).sort(([a], [b]) => a.localeCompare(b))) {
    responses[status] = Object.keys(deref(raw).content ?? {}).sort();
  }
  const statuses = Object.keys(responses).filter((s) => /^\d{3}$/.test(s)).map(Number);
  const security = (operation.security ?? doc.security ?? []).flatMap((entry) => Object.keys(entry)).sort();
  const entry = policy[operationId];
  if (!entry) fail(`${operationId} has no retry-policy.json entry`);
  return {
    operationId,
    kind,
    method: method.toUpperCase(),
    path,
    basePath: kind === 'webhook' ? null : basePath(operation.servers ?? pathItem.servers ?? doc.servers),
    parameters,
    idempotencyKey: parameters.header.some((p) => p.name.toLowerCase() === 'idempotency-key'),
    csrfHeader: parameters.header.some((p) => p.name.toLowerCase() === 'x-csrf-token'),
    requestBody: body ? { required: body.required === true, mediaTypes: Object.keys(body.content ?? {}).sort() } : null,
    responses,
    successStatuses: statuses.filter((s) => s >= 200 && s < 300),
    redirectStatuses: statuses.filter((s) => s >= 300 && s < 400),
    security,
    policy: entry,
  };
}

function routes() {
  const table = {};
  const add = (entry) => {
    if (table[entry.operationId]) fail(`duplicate operationId ${entry.operationId}`);
    table[entry.operationId] = entry;
  };
  for (const [path, pathItem] of Object.entries(doc.paths ?? {})) {
    for (const method of METHODS) {
      const operation = pathItem[method];
      if (!operation) continue;
      if (!operation.operationId) fail(`${method.toUpperCase()} ${path} has no operationId`);
      add(route(operation.operationId, method, path, pathItem, operation, 'path'));
    }
  }
  for (const [name, pathItem] of Object.entries(doc.webhooks ?? {})) {
    for (const method of METHODS) {
      const operation = pathItem[method];
      if (operation) add(route(operation.operationId, method, name, pathItem, operation, 'webhook'));
    }
  }
  for (const id of Object.keys(policy)) if (!table[id]) fail(`retry-policy.json names unknown operationId ${id}`);
  return Object.fromEntries(Object.keys(table).sort().map((id) => [id, table[id]]));
}

const digest = createHash('sha256').update(source).digest('hex');
const meta = {
  openapiVersion: String(doc.info?.version ?? ''),
  openapiSha256: digest,
  generator: GENERATOR,
  routingGenerator: ROUTING_GENERATOR,
};
const expectedManifest = { openapiVersion: meta.openapiVersion, generator: GENERATOR, routingGenerator: ROUTING_GENERATOR };


const outputs = {
  // A default is applied by the server; it does not make a request field required.
  [OUT.openapi]: HEADER + astToString(await openapiTS(publicContract(doc), { silent: true, defaultNonNullable: false })),
  [OUT.routing]: HEADER
    + "import type { RouteEntry } from '../routing-types.js';\n\n"
    + `export const routing = ${JSON.stringify(routes(), null, 2)} as const satisfies Record<string, RouteEntry>;\n\n`
    + 'export type OperationId = keyof typeof routing;\n',
};
meta.outputSha256 = outputDigest(outputs[OUT.openapi], outputs[OUT.routing]);
outputs[OUT.meta] = HEADER + `export const BUILD_INFO = ${JSON.stringify(meta, null, 2)} as const;\n`;

if (process.argv.includes('--check')) {
  const stale = Object.entries(outputs).filter(([path, text]) => {
    try { return readFileSync(path, 'utf8') !== text; } catch { return true; }
  }).map(([path]) => path.slice(path.indexOf('src/')));
  if (JSON.stringify(manifest.octocove) !== JSON.stringify(expectedManifest)) stale.push('package.json "octocove" build record');
  if (stale.length) fail(`stale generated client output (OpenAPI or policy changed without regeneration): ${stale.join(', ')}`);
  process.stdout.write(`Generated client is current (OpenAPI ${meta.openapiVersion}, ${GENERATOR}, ${ROUTING_GENERATOR}).\n`);
} else {
  for (const [path, text] of Object.entries(outputs)) writeFileSync(path, text);
  if (JSON.stringify(manifest.octocove) !== JSON.stringify(expectedManifest)) {
    manifest.octocove = expectedManifest;
    writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2) + '\n');
  }
  process.stdout.write(`Generated ${Object.keys(outputs).length} files.\n`);
}
